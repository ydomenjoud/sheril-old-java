        <blockquote>
            <p>L'homme se préparait à cet affrontement depuis des siècles. Peut-être par instinct, peut-être qu'il ne
                pouvait pas vivre sans un ennemi contre lequel se battre. Pendant des siècles, il développa une science
                pour se préparer au combat dans l'espace contre une autre intelligence.</p>

            <p>La science était l'alliée de l'homme ; elle lui avait murmuré les limites des vaisseaux et des armes
                spatiales ; vitesse, accélération, énergie, tous ces paramètres étaient bornés par des constantes
                universelles. Pendant toutes ces années où les combattants s'étaient préparés, ils avaient affronté
                virtuellement des vaisseaux parfaits, des vaisseaux dont les seules limites étaient les limites
                physiques de l'univers. Ainsi l'homme connaissait un peu son ennemi, il savait qu'il n'aurait jamais à
                affronter pire que ce qu'il avait combattu pendant tout ce temps ; et quand l'ennemi apparut, il était
                comme l'humanité l'avait imaginé.</p>

            <p>Alors la guerre commença.</p>

            <p>Les premiers vaisseaux adverses firent leur apparition loin de la zone contrôlée par les hommes, dans une
                partie de l'univers éloignée de la terre de plusieurs milliers d'années-lumière. L'ennemi attaqua des
                sondes d'exploration.</p>

            <p>Et l'homme riposta ; aveuglément. Les vaisseaux de l'humanité étaient innombrables : des milliers de
                points brillants qui parcouraient l'univers à des vitesses fantastiques, emportant en leur sein une
                incroyable puissance de feu.</p>

            <p>Ainsi, quand la guerre commença, l'homme écrasa son ennemi sans nom.</p>

            <p>Chaque jour on faisait des bilans. Les pertes de l'ennemi se comptaient en centaines de vaisseaux
                détruits quotidiennement. Mais sa flotte était comme celle de l'humanité : immense. L'affrontement
                consistait à détruire les vaisseaux, et à détruire ensuite les planètes qui produisaient les
                vaisseaux.</p>

            <p>Mais telles étaient les nécessités de la guerre. L'humanité éliminait des systèmes solaires entiers
                chaque jour. Les bombes nova allumaient dans le ciel de petites étoiles bleues qui immédiatement
                mouraient. Et l'ennemi reculait. C'était le premier temps, celui qui fut appelé ensuite le temps de la
                Victoire.</p>

            <p>Quand les premières défaites se produisirent, l'humanité refusa de comprendre que quelque chose avait
                changé. Elle gagnait depuis si longtemps que cela lui paraissait impossible. Les stratèges furent pris
                au dépourvu, leur science de la guerre leur avait jusque-là donné un sentiment de parfaite
                invulnérabilité.</p>

            <p>Les stratégies, ces œuvres si brillantes, si pures, semblaient à présent n'être que des constructions
                naïves, pleines de failles et de faiblesses où l'ennemi enfonçait ses griffes. Les choses avaient
                changé. Et ce fut un tournant dans la guerre. Les humains durent laisser du terrain à l'ennemi et des
                planètes furent évacuées par centaines, car Il voulait regagner les centres de production.</p>

            <p>Ce fut le temps de la retraite.</p>

            <p>L'homme était confronté à plus fort que lui. La race humaine avait trouvé un prédateur qui lui était
                supérieur. Alors la race humaine devait devenir plus forte que ce prédateur. Elle devait s'adapter,
                grandir, devenir à son tour puissante et terrible.</p>

            <p>Vint le temps des mutants.</p>

            <p>On installa sur plusieurs planètes des émetteurs de radiations, colonnes bleutées à la couleur si
                caractéristique, qui irradiaient les populations de rayonnements mutagènes.</p>

            <p>Et naquirent des monstres aux yeux de l'humanité. Ces planètes terribles ressemblaient à l'enfer. Ceux
                qui y vivaient n'y étaient plus que des caricatures d'êtres humains ; monstrueuses créations, pièces
                d'un plan qui les dépassait, ils traînaient leurs existences misérables, endurant leurs mutations
                physiques grotesques et répugnantes, ou mourant dans les souffrances de cancers foudroyants.</p>

            <p>Pendant plusieurs siècles, ces enfers produisirent des individus aux étranges talents, mais on attendait
                toujours ceux qui pourraient lutter, ceux dont les capacités mentales seraient telles qu'ils pourraient
                gagner face à l'ennemi.</p>

            <p>On vit apparaître :</p>
            <ul>
                <li><strong class="race3">les Yoksors</strong>, qui devinrent les stratèges sauveurs de l'humanité ;
                </li>
                <li><strong class="race4">les Fergoks</strong>, utilisés aux combats et dans les épreuves de force en
                    raison de leur forte carrure ;
                </li>
                <li><strong class="race1">les Atalantes</strong>, gardant le plus l'aspect et la tradition des humains
                    avec une paire de branchies supplémentaire ;
                </li>
                <li>et sur certains systèmes, <strong class="race0">les Fremens</strong>, ayant réussi à dompter les
                    nouvelles créatures mutantes telles que les vers des sables, créatures se déplaçant sous le sol du
                    désert et pouvant engloutir une ville en quelques secondes seulement.
                </li>
            </ul>

            <p>À nouveau, l'ennemi se faisait écraser à chaque fois qu'un des nouveaux stratèges dirigeait une flotte
                humaine. Et les anciens soldats, voyant leurs élèves se battre si brillamment, comprirent que leur temps
                était fini ; à côté de ces nouveaux guerriers, ils n'étaient que des simples d'esprit.</p>

            <p>Et les mutants, d'une voix et d'une seule, exigèrent que toute l'humanité subisse le même châtiment que
                celui qui leur avait été imposé : la mutation.</p>

            <p>Toute l'humanité disparut et fut remplacée par les mutants, qui fondèrent chacun de leur côté une
                civilisation nouvelle, à partir des lambeaux de l'humanité.</p>

            <p>Vous êtes dans Sheril, le monde vu par ceux qui ont été traités comme des bêtes par leurs frères.</p>
